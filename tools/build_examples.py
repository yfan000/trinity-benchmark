#!/usr/bin/env python3
"""Regenerate examples/ from the v8 corpus.

Generated, never hand-written. A walkthrough written by hand drifts the moment a prompt or a
rule changes, and then it misleads a reader about what the harness does. Re-run this after any
change to the corpus or the rubric.

    python tools/build_examples.py
"""
from __future__ import annotations
import collections, json, pathlib, statistics, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from judge.skills.loader import load as load_skill          # noqa: E402

RUBRIC = "r28"                     # the library as it stands
GRADED_UNDER = "r27"               # what the shipped grades were produced under
# not_copied_from_example was removed in r28 but appears in the r27 grades. Label it rather
# than showing a bare em dash, so a reader is not left wondering why a rule has no severity.
RETIRED = {"INP.common.not_copied_from_example": "removed in r28"}

CORPUS = ROOT / "data" / "corpus" / "v8"
OUT = ROOT / "examples"
SLUG = {"Software selection": "software_selection", "Input preparation": "input_preparation",
        "Resource selection": "resource_selection", "Batch job creation": "batch_job_creation"}

# One anchor per subtask, chosen to show the task honestly. Input preparation deliberately
# shows a FAILING answer: 21% is the finding, and a passing example would misrepresent it.
PICK = {
    "Software selection":  ("nemotron-3-ultra", "nwchem",  "polaris", "a clean pass"),
    "Input preparation":   ("llama-3.1-8b",     "alphafold", "perlmutter",
                            "a failure — the model wrote the wrong protein"),
    "Resource selection":  ("gemma-4-31b",      "lammps",  "polaris", "a clean pass"),
    "Batch job creation":  ("nemotron-3-ultra", "hpl",     "crux",    "a clean pass"),
}
ARM = "base"


def load(name):
    p = CORPUS / name
    return [json.loads(l) for l in p.open()] if p.exists() else []


def main() -> int:
    samples = {(r["subtask"], r["app"], r["system"]): r for r in load(f"samples_v8{ARM}.jsonl")}
    answers = {(r["model"], r["subtask"], r["app"], r["system"]): r
               for r in load(f"answers_v8{ARM}.jsonl")}
    grades = collections.defaultdict(list)
    for i in (1, 2, 3):
        for r in load(f"grades_v8{ARM}__gpt56terra__r27__SKILLMODE__run{i}.jsonl"):
            grades[(r["model"], r["subtask"], r["app"], r["system"])].append(r)

    index = ["# Worked examples\n",
             "One end-to-end walkthrough per subtask, taken verbatim from corpus v8 — the prompt a",
             "model received, Claude's reference answer, what the model actually wrote, and every",
             "requirement verdict with the judge's evidence.\n",
             "Generated by `tools/build_examples.py`; do not edit by hand.\n"]

    for st, (model, app, system, why) in PICK.items():
        key = (model, st, app, system)
        s, a, gs = samples.get((st, app, system)), answers.get(key), grades.get(key, [])
        if not (s and a and gs):
            print(f"  SKIP {st}: missing corpus rows")
            continue
        d = OUT / SLUG[st]
        d.mkdir(parents=True, exist_ok=True)
        med = lambda f: statistics.median_low([g.get(f, 0) for g in gs])
        fatal = sum(bool(g.get("fatal_error")) for g in gs) > len(gs) / 2
        ok = med("correctness") == 2 and med("completeness") == 2 and med("usability") == 2 and not fatal

        (d / "prompt.md").write_text(f"# Prompt — {app}@{system}\n\n"
                                     f"Subtask: **{st}**. Base arm, exactly as the model received it.\n\n"
                                     f"````\n{s['prompt']}\n````\n")
        (d / "reference.md").write_text(
            f"# Reference answer — {app}@{system}\n\nWritten by Claude and shown to the judge as "
            f"*one* correct answer, never as the correct one. The judge is told explicitly not to "
            f"deduct for differing from it where the requirements are met.\n\n"
            f"````\n{s.get('reference') or '(none)'}\n````\n")
        (d / f"answer-{model}.md").write_text(
            f"# Answer — {model}\n\n{app}@{system}, {st}. **{'PASS' if ok else 'FAIL'}** "
            f"(correctness {med('correctness')}/2, completeness {med('completeness')}/2, "
            f"usability {med('usability')}/2{', fatal' if fatal else ''}).\n\n"
            f"````\n{a.get('answer') or ''}\n````\n")

        skill = load_skill(st, app, system, rubric_id=RUBRIC)
        sev = {r["id"]: r.get("severity", "major") for r in skill.requirements}
        ids = set().union(*[set(g.get("requirements") or {}) for g in gs])
        rows = []
        for rid in sorted(ids):
            vs = [(g.get("requirements") or {}).get(rid, {}) for g in gs]
            verds = [v.get("verdict") for v in vs if v.get("verdict")]
            if not verds:
                continue
            top = collections.Counter(verds).most_common(1)[0][0]
            evid = next((v.get("evidence", "") for v in vs if v.get("verdict") == top), "")
            flip = " ⚠︎ flipped across runs" if len(set(verds)) > 1 else ""
            label = sev.get(rid) or RETIRED.get(rid, "—")
            rows.append(f"| `{rid}` | {label} | **{top}**{flip} | {evid.replace('|','\\|')} |")
        (d / "verdicts.md").write_text(
            f"# Verdicts — {model} on {app}@{system}\n\n"
            f"Majority across three judge replicates, judged by gpt56terra under rubric "
            f"**{GRADED_UNDER}**. Severities shown are the current library, **{RUBRIC}** "
            f"(sha `{skill.rubric_sha256}`).\n\n"
            f"| requirement | severity | verdict | judge's evidence |\n|---|---|---|---|\n"
            + "\n".join(rows) + "\n")

        nviol = sum(1 for r in rows if "**violated**" in r)
        (d / "README.md").write_text(
            f"# {st}\n\n**{app}@{system}**, answered by `{model}` — {why}.\n\n"
            f"{len(rows)} requirements applied, {nviol} violated. "
            f"Result: **{'PASS' if ok else 'FAIL'}**.\n\n"
            f"- [`prompt.md`](prompt.md) — what the model saw\n"
            f"- [`reference.md`](reference.md) — Claude's reference answer\n"
            f"- [`answer-{model}.md`](answer-{model}.md) — what it wrote\n"
            f"- [`verdicts.md`](verdicts.md) — every requirement and the judge's evidence\n")
        index.append(f"- **[{st}]({SLUG[st]}/)** — `{app}@{system}`, {model}: "
                     f"{'pass' if ok else 'fail'}, {nviol} of {len(rows)} requirements violated")
        print(f"  {SLUG[st]:<22}{'PASS' if ok else 'FAIL'}  {nviol}/{len(rows)} violated")

    (OUT / "README.md").write_text("\n".join(index) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
